#!/usr/bin/env node
// Writes src/worker/client.ts from .github/release/release-client.sh, the one copy of the
// publish client: the release workflow runs it, and the Worker serves it at /release/client.sh.
// test/client.test.ts fails when they differ.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../../../.github/release/release-client.sh", import.meta.url));
const target = fileURLToPath(new URL("../src/worker/client.ts", import.meta.url));
const text = await readFile(source, "utf8");
await writeFile(
  target,
  "// Generated by scripts/sync-client.mjs from .github/release/release-client.sh. Do not edit.\n" +
    "export default " + JSON.stringify(text) + ";\n",
);
console.log("wrote " + target);
