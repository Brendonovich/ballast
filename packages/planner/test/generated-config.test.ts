import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";
import { generatedConfigText, writeGeneratedConfig } from "../src/index.ts";

describe("generated configs", () => {
  it.effect("regenerates an unmodified file and keeps an edited one", () =>
    Effect.gen(function* () {
      const root = yield* Effect.promise(() =>
        mkdtemp(join(tmpdir(), "ballast-generated-config-")),
      );
      yield* Effect.addFinalizer(() =>
        Effect.promise(() => rm(root, { recursive: true, force: true })).pipe(Effect.ignore),
      );
      const file = join(root, "tsconfig.json");
      const old = {
        compilerOptions: { jsx: "preserve" },
        include: ["old/**/*.ts", "../src/**/*.ts"],
      };
      const next = {
        compilerOptions: { jsx: "preserve" },
        include: ["new/**/*.ts"],
      };
      yield* Effect.promise(() => writeFile(file, generatedConfigText(old), "utf8"));

      const regenerated = yield* Effect.promise(() =>
        writeGeneratedConfig(file, next),
      );
      expect(regenerated).toEqual({ wrote: true, edited: false });
      const afterRegenerate = yield* Effect.promise(() => readFile(file, "utf8"));
      expect(afterRegenerate).not.toContain("../src/**/*.ts");
      expect(afterRegenerate).toContain("new/**/*.ts");
      expect(afterRegenerate).toContain("generated by ballast; edits are kept");

      const editedText = afterRegenerate + "// keep me\n";
      yield* Effect.promise(() => writeFile(file, editedText, "utf8"));
      const kept = yield* Effect.promise(() => writeGeneratedConfig(file, old));
      expect(kept).toEqual({ wrote: false, edited: true });
      expect(yield* Effect.promise(() => readFile(file, "utf8"))).toBe(editedText);
    }),
  );
});
