import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";

/**
 * Generated configs carry this notice so a later run can tell its own output
 * from a user-owned file. The marker also stores a hash of the generated text
 * (with the hash itself replaced by a fixed placeholder), which detects any
 * edit, including comments or whitespace.
 */
export const GENERATED_CONFIG_NOTICE = "generated by ballast; edits are kept";

const NOTICE_PREFIX = GENERATED_CONFIG_NOTICE + "; hash=";
const HASH_PLACEHOLDER = "__BALLAST_GENERATED_CONFIG_HASH__";
const MARKER_KEY = "//";

export type ConfigObject = Readonly<Record<string, unknown>>;

const isRecord = (value: unknown): value is Readonly<Record<string, unknown>> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/**
 * tsconfig is JSONC in practice. Strip comments and trailing commas before
 * reading fields. A malformed config returns undefined.
 */
export const parseConfigText = (
  text: string,
): Readonly<Record<string, unknown>> | undefined => {
  let stripped = "";
  let inString = false;
  let escaped = false;
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index] ?? "";
    const next = text[index + 1];
    if (inString) {
      stripped += character;
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') {
      inString = true;
      stripped += character;
      continue;
    }
    if (character === "/" && next === "/") {
      while (index < text.length && text[index] !== "\n") index += 1;
      stripped += "\n";
      continue;
    }
    if (character === "/" && next === "*") {
      index += 2;
      while (index < text.length && !(text[index] === "*" && text[index + 1] === "/")) index += 1;
      index += 1;
      stripped += " ";
      continue;
    }
    if (character === ",") {
      let lookahead = index + 1;
      while (lookahead < text.length && /\s/.test(text[lookahead] ?? "")) lookahead += 1;
      const following = text[lookahead];
      if (following === "}" || following === "]") continue;
    }
    stripped += character;
  }
  try {
    const parsed: unknown = JSON.parse(stripped);
    return isRecord(parsed) ? parsed : undefined;
  } catch {
    return undefined;
  }
};

const withoutMarker = (config: ConfigObject): ConfigObject => {
  const copy: Record<string, unknown> = { ...config };
  delete copy[MARKER_KEY];
  return copy;
};

const markerHash = (config: ConfigObject): string | undefined => {
  const marker = config[MARKER_KEY];
  if (typeof marker !== "string" || !marker.startsWith(NOTICE_PREFIX)) return undefined;
  const hash = marker.slice(NOTICE_PREFIX.length).trim();
  return /^[0-9a-f]{64}$/.test(hash) ? hash : undefined;
};

const hashText = (text: string): string =>
  createHash("sha256").update(text).digest("hex");

const render = (config: ConfigObject, hash: string): string =>
  JSON.stringify(
    {
      ...config,
      [MARKER_KEY]: NOTICE_PREFIX + hash,
    },
    null,
    2,
  ) + "\n";

/** Render a generated config with its marker and edit-detection hash. */
export const generatedConfigText = (config: ConfigObject): string => {
  const hash = hashText(render(config, HASH_PLACEHOLDER));
  return render(config, hash);
};

export interface GeneratedConfigWrite {
  readonly wrote: boolean;
  readonly edited: boolean;
}

export interface GeneratedConfigOptions {
  /** Shapes from older generators that are safe to replace with the new one. */
  readonly legacy?: ReadonlyArray<ConfigObject>;
  /** Recognize another unmarked shape as generated (for pre-marker files). */
  readonly generatedShape?: (config: ConfigObject) => boolean;
}

/**
 * Write a generated config using the marked-file policy:
 * - a missing file is created;
 * - an unmodified generated file is updated in place;
 * - an edited generated file is kept and reported;
 * - an unknown user file is kept untouched.
 */
export const writeGeneratedConfig = async (
  file: string,
  config: ConfigObject,
  options: GeneratedConfigOptions = {},
): Promise<GeneratedConfigWrite> => {
  const desired = generatedConfigText(config);
  if (!existsSync(file)) {
    await writeFile(file, desired, "utf8");
    return { wrote: true, edited: false };
  }
  const text = await readFile(file, "utf8");
  const parsed = parseConfigText(text);
  if (parsed === undefined) {
    return { wrote: false, edited: text.includes(GENERATED_CONFIG_NOTICE) };
  }
  const stored = markerHash(parsed);
  if (stored !== undefined) {
    const currentHash = hashText(text.replace(stored, HASH_PLACEHOLDER));
    if (currentHash !== stored) return { wrote: false, edited: true };
    if (text === desired) return { wrote: false, edited: false };
    await writeFile(file, desired, "utf8");
    return { wrote: true, edited: false };
  }
  const current = withoutMarker(parsed);
  const currentJson = JSON.stringify(current);
  const legacy =
    options.generatedShape?.(current) === true ||
    options.legacy?.some((candidate) => JSON.stringify(candidate) === currentJson) === true ||
    currentJson === JSON.stringify(config);
  if (legacy) {
    await writeFile(file, desired, "utf8");
    return { wrote: true, edited: false };
  }
  return { wrote: false, edited: false };
};
